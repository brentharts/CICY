"""
Tests for pyCICY.sixsphere_gauge (Part IX: the fibre structure and its
holonomy, after Gomes's gauge theory without principal bundles).

  [1] structure     the invariant tensors of degree <= 2 are gamma, delta^,
                    Q0, eta, gamma^2, delta^^2 and <I, gamma (x) delta^>,
                    with delta^ = Q0(gamma, .)
  [2] gauge group   the automorphisms of (Q0, gamma) are L(M) h(c, s), the
                    integral Jacobi group; the row r is forced; the
                    Heisenberg law has centre 6 omega
  [3] index 12      chi = alpha + f is a character; chi(T1) = chi(T2) = 0,
                    chi(z) = 1; explicit words; <T1, T2> = ker chi
  [4] closure       the Lie algebra generated by unipotent logs is the full
                    6-dimensional Jacobi algebra
  [5] period domain G(R) acts by the Jacobi laws, preserves D; orbit
                    dimension 5, stabiliser SO(2)
  [6] classes       the four Part VII classes are d = 1, 2, 3, 6; d | p and
                    the least |p| is d; the central index is 12 in all four
                    (observed)
  [7] controls      Levi lifts: chi = (4, 9), cusp rank 1; a twisted T1
                    (times z) leaves ker chi; f with the even refinement is
                    not a homomorphism; a perturbed Q0 has no gamma-stabiliser
                    containing T1

Run with:  python3 tests/test_sixsphere_gauge.py   or   python3 run_tests.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sympy import Matrix, eye

from pyCICY import sixsphere as S
from pyCICY import sixsphere_gauge as G
from pyCICY import sixsphere_search as SR

FAILURES = []


def check(name, got, want):
    ok = got == want
    print("  {:<58} {:>12} {}".format(name, str(got)[:12],
                                      "ok" if ok else "FAIL want " + str(want)))
    if not ok:
        FAILURES.append(name)


def check_true(name, cond):
    print("  {:<58} {:>12} {}".format(name, str(bool(cond)),
                                      "ok" if cond else "FAIL"))
    if not cond:
        FAILURES.append(name)


def test_structure():
    print("\n[1] the structure every fibre carries")
    it = G.invariant_tensors()
    check("dimensions V, V*, VV, V*V*, End",
          tuple(it["dims"][k] for k in ("V", "V*", "VV", "V*V*", "End")),
          (1, 1, 2, 2, 2))
    check_true("V^G = <gamma>", it["V_is_gamma"])
    check_true("V*^G = <delta^>", it["V*_is_delta_hat"])
    check_true("the alternating invariant is Q0", it["alternating_is_Q0"])
    check_true("delta^ = Q0(gamma, .)", it["delta_hat = Q0(gamma, .)"])
    check_true("commutant <I, gamma (x) delta^>",
               it["commutant_is_I_and_gamma_delta"])


def test_gauge_group():
    print("\n[2] the derived gauge group: the integral Jacobi group")
    sg = G.structure_group()
    for k, v in sg.items():
        check_true(k, v)
    M, h = G.split(S.T1)
    check("T1 = L(M1) h(-1, 0, 2)", (M.tolist(), h), ([[-1, 1], [-1, 0]], (-1, 0, 2)))
    M, h = G.split(S.T2)
    check("T2 = L(S) h(0, -1, -3)", (M.tolist(), h), ([[0, -1], [1, 0]], (0, -1, -3)))
    M, h = G.split(S.T1 * S.T2)
    check("T0^-1 = L(T) z^-1", (M.tolist(), h), ([[1, 1], [0, 1]], (0, 0, -1)))


def test_index():
    print("\n[3] the holonomy group is ker chi, of index 12")
    check_true("f is a homomorphism (16 cases mod 2)",
               G.f_is_homomorphism()["ok"])
    for k, v in G.f_is_invariant().items():
        check_true(k, v)
    a = G.alpha()
    check_true("alpha respects S^4, (ST)^3 = S^2", all(a["relations"].values()))
    check_true("M2 = S, M1 = T S^-1", all(a["words"].values()))
    check("alpha(M1), alpha(M2), alpha(T)",
          (a["values"]["M1"], a["values"]["M2"], a["values"]["T"]), (4, 9, 1))
    hi = G.holonomy_index()
    check("chi(T1), chi(T2), chi(T1 T2)",
          (hi["chi(T1)"], hi["chi(T2)"], hi["chi(T0^-1 = T1 T2)"]), (0, 0, 0))
    check("chi(z) for z: delta -> delta + gamma", hi["chi(z)"], 1)
    check_true("explicit words give h(1,0,6), h(0,1,6), h(-1,0,6)",
               hi["words_ok"])
    check_true("z^12 = h(1,0,6) h(-1,0,6) in H", hi["z^12 in H"])
    check_true("<T1, T2> = ker chi (proved)", hi["proved"])


def test_closure():
    print("\n[4] Zariski closure through the Lie algebra")
    za = G.zariski_lie_algebra()
    check("dim of the generated Lie algebra", za["dim generated"], 6)
    check("dim of the stabiliser of (Q0, gamma)", za["dim stabiliser"], 6)
    check_true("generated algebra lies in it", za["inside stabiliser"])


def test_period_domain():
    print("\n[5] the real Jacobi group on the period domain")
    pa = G.period_domain_action()
    for k, v in pa.items():
        check_true(k + ": 6 mu shape, D invariant",
                   v["shape_ok"] and v["D_invariant"])
    t, mu, beta = S.TAU, S.MU, S.BETA
    check("centre acts by beta -> beta + t",
          str(pa["h(0,0,t)"]["law"]), str((t, mu, beta + G.symbols("t", real=True))))
    sd = G.stabiliser_dimension()
    check("orbit dimension at (i, 0, -i)", sd["orbit_dim"], 5)
    check_true("the rotation k_theta fixes the point", sd["rotation_fixes_point"])


def test_classes():
    print("\n[6] the four classes of Part VII")
    cd = G.class_divisibility(3)
    check("survivors at box 3", cd["survivors"], 32)
    check("divisibilities d of Q(gamma, .)", cd["d_values"], [1, 2, 3, 6])
    check("eight survivors per d", cd["count_by_d"], {1: 8, 2: 8, 3: 8, 6: 8})
    check("Pfaffian of the primitive form", cd["pfaffians"], [6])
    check_true("d divides every reachable p", cd["d_divides_p"])
    check_true("gcd of reachable p is d", cd["gcd_equals_d"])
    check_true("least nonzero |p| is d", cd["least_|p|_equals_d"])
    check("the paper's data: (d, Pf)", cd["paper"], (1, 6))
    cls = SR.classify(SR.funnel(3)["survivors"])
    idx = sorted(G.central_index(*c["rep"], max_elements=60000)["gcd"]
                 for c in cls)
    check("central index in each class (word search, observed)", idx,
          [12, 12, 12, 12])


def test_controls():
    print("\n[7] controls")
    lc = G.levi_lift_control()
    check_true("Levi lifts have orders 3 and 4", all(lc["orders"]))
    check("chi of the Levi lifts", lc["chi"], (4, 9))
    check("their cusp has rank 1, not 2", lc["rank N"], 1)
    z = G.heis(0, 0, 1)
    check("T1 z has chi 1: outside ker chi", G.chi(S.T1 * z), 1)
    check_true("T1 z has infinite order ((T1 z)^3 = z^3)",
               (S.T1 * z) ** 3 == z ** 3 and z ** 3 != eye(4))
    even_q = lambda c: 0
    bad = 0
    import itertools
    for c, cp in itertools.product(itertools.product((0, 1), repeat=2), repeat=2):
        om = c[0] * cp[1] - c[1] * cp[0]
        if (6 * om) % 12:
            bad += 1
    check_true("without the refinement q, s mod 12 is not a homomorphism",
               bad > 0)
    Q = S.Q0.copy()
    Q[1, 2], Q[2, 1] = 5, -5
    check_true("T1 does not preserve a perturbed form (6 -> 5)",
               S.T1.T * Q * S.T1 != Q)


def main():
    for section in (test_structure, test_gauge_group, test_index, test_closure,
                    test_period_domain, test_classes, test_controls):
        try:
            section()
        except Exception as exc:
            print("  {:<58} {:>12} FAIL".format(section.__name__ + " raised",
                                                type(exc).__name__))
            print("      " + str(exc)[:300])
            FAILURES.append("%s raised %s" % (section.__name__,
                                              type(exc).__name__))
    print()
    if FAILURES:
        print("FAILED: %d" % len(FAILURES))
        for f in FAILURES:
            print("  - " + f)
        return 1
    print("all sixsphere_gauge tests passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
