def period_domain_action():
    r"""One-parameter subgroups of G(R) through laws_from_lattice; D invariant."""
    t = symbols("t", real=True)
    x, y, u, v, e, f = symbols("x y u v e f", real=True)
    sub = {S.TAU: x + _I * y, S.MU: u + _I * v, S.BETA: e + _I * f}
    D = f - 6 * v ** 2 / y
    gens = {"h(t,0,0)": heis(t, 0, 0), "h(0,t,0)": heis(0, t, 0),
            "h(0,0,t)": heis(0, 0, t),
            "L[[1,t],[0,1]]": levi(Matrix([[1, t], [0, 1]])),
            "L[[1,0],[t,1]]": levi(Matrix([[1, 0], [t, 1]])),
            "L[[e^t,0],[0,e^-t]]": levi(Matrix([[exp(t), 0], [0, exp(-t)]]))}
    out = {}
    for k, g in gens.items():
        d = S.laws_from_lattice(g)
        law = [l.subs(sub, simultaneous=True) for l in d["law"]]
        Dg = im(law[2]) - 6 * im(law[1]) ** 2 / im(law[0])
        out[k] = {"law": tuple(simplify(l) for l in d["law"]),
                  "shape_ok": d["shape_ok"],
                  "D_invariant": simplify(expand_complex(Dg - D)) == 0}
    return out


def stabiliser_dimension(D0=-1):
    r"""Rank of the infinitesimal action at (tau, mu, beta) = (i, 0, i D0).

    The six generators' velocity vectors in R^6 = (Re, Im of tau, mu, beta);
    the rank is the orbit dimension, 6 minus it the stabiliser dimension.
    The rotation k_theta = [[cos, sin], [-sin, cos]] fixes the point exactly.
    """
    t = symbols("t", real=True)
    pt = {S.TAU: _I, S.MU: 0, S.BETA: _I * D0}
    gens = [heis(t, 0, 0), heis(0, t, 0), heis(0, 0, t),
            levi(Matrix([[1, t], [0, 1]])), levi(Matrix([[1, 0], [t, 1]])),
            levi(Matrix([[exp(t), 0], [0, exp(-t)]]))]
    rows = []
    for g in gens:
        law = S.laws_from_lattice(g)["law"]
        vel = [simplify(l.diff(t).subs(t, 0).subs(pt)) for l in law]
        row = []
        for z in vel:
            row += [simplify(expand_complex(z).as_real_imag()[0]),
                    simplify(expand_complex(z).as_real_imag()[1])]
        rows.append(row)
    rank = Matrix(rows).rank()
    th = symbols("theta", real=True)
    k = levi(Matrix([[cos(th), sin(th)], [-sin(th), cos(th)]]))
    law = S.laws_from_lattice(k)["law"]
    fixed = all(simplify(expand_complex(l.subs(pt) - pt[z])) == 0
                for l, z in zip(law, (S.TAU, S.MU, S.BETA)))
    return {"orbit_dim": rank, "stabiliser_dim": 6 - rank,
            "rotation_fixes_point": fixed}


