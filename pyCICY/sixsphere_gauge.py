def _primitive_alt_form(T1, T2):
    xs = symbols("x0:16")
    X = Matrix(4, 4, xs)
    eqs = list(X + X.T)
    for T in (Matrix(T1), Matrix(T2)):
        eqs += list(T.T * X * T - X)
    sol = list(linsolve(eqs, xs))[0]
    free = list(set().union(*[e.free_symbols for e in sol]))
    if len(free) != 1:
        return None
    Q = Matrix(4, 4, [e.subs(free[0], 1) for e in sol])
    den = 1
    for x in Q:
        den = den * Rational(x).q // gcd(den, Rational(x).q)
    Q = Q * den
    g = 0
    for x in Q:
        g = gcd(g, int(x))
    return Q / g


def _divisibility(T1, T2):
    Q = _primitive_alt_form(T1, T2)
    row = Q.row(0)                         # Q(gamma, .)
    d = 0
    for x in row:
        d = gcd(d, int(x))
    pf = Q[0, 1] * Q[2, 3] - Q[0, 2] * Q[1, 3] + Q[0, 3] * Q[1, 2]
    return d, abs(int(pf)), Q


def class_divisibility(box=3, ell_box=3):
    r"""For every funnel survivor: the divisibility d of Q(gamma, .), the
    Pfaffian, and the gcds of the reachable p with 12."""
    from . import sixsphere_search as SR
    survivors = SR.funnel(box)["survivors"]
    rows = []
    for T1, T2 in survivors:
        d, pf, _ = _divisibility(T1, T2)
        ells = SR.admissible_ells(T1, T2, box=ell_box)
        ps = {12 * l0 - 4 * a - 3 * b
              for a in ells[0] for b in ells[1] for l0 in (-1, 0, 1)}
        g = 0
        for p in ps:
            g = gcd(g, p)
        rows.append({"d": d, "pfaffian": pf, "gcd of reachable p": g,
                     "d divides every p": all(p % d == 0 for p in ps),
                     "least nonzero |p|": min(abs(p) for p in ps if p)})
    by_d = {}
    for r in rows:
        by_d.setdefault(r["d"], []).append(r)
    return {"survivors": len(rows),
            "d_values": sorted(by_d),
            "count_by_d": {d: len(v) for d, v in sorted(by_d.items())},
            "pfaffians": sorted({r["pfaffian"] for r in rows}),
            "d_divides_p": all(r["d divides every p"] for r in rows),
            "gcd_equals_d": all(r["gcd of reachable p"] == r["d"] for r in rows),
            "least_|p|_equals_d": all(r["least nonzero |p|"] == r["d"]
                                      for r in rows),
            "paper": _divisibility(np.array(S.T1.tolist()),
                                   np.array(S.T2.tolist()))[:2]}


def central_index(T1, T2, max_elements=400000):
    """The gcd of the s with h(0, 0, s) in <T1, T2>, by a word search."""
    T1 = np.array(Matrix(T1).tolist(), dtype=object)
    T2 = np.array(Matrix(T2).tolist(), dtype=object)
    gens = [T1, T1.dot(T1), T2, T2.dot(T2), T2.dot(T2).dot(T2)]
    I4 = np.eye(4, dtype=object)
    seen = {tuple(I4.flatten())}
    frontier = [I4]
    g = 0
    while frontier and len(seen) < max_elements:
        nxt = []
        for A in frontier:
            for G in gens:
                B = A.dot(G)
                k = tuple(B.flatten())
                if k in seen:
                    continue
                seen.add(k)
                nxt.append(B)
                if (B - I4)[1:, :].any() or B[0, 1] or B[0, 2]:
                    continue
                g = gcd(g, int(B[0, 3]))
        frontier = nxt
    return {"gcd": g, "elements": len(seen)}


def status_gauge(box=3):
    """Run every check of Part IX and print a summary; returns True if all pass."""
    checks = []

    def ok(name, cond):
        checks.append((name, bool(cond)))

    it = invariant_tensors()
    ok("invariant tensors: gamma, delta^, Q0 unique", it["V_is_gamma"]
       and it["V*_is_delta_hat"] and it["alternating_is_Q0"])
    ok("delta^ = Q0(gamma, .)", it["delta_hat = Q0(gamma, .)"])
    ok("commutant <I, gamma (x) delta^>", it["commutant_is_I_and_gamma_delta"])
    sg = structure_group()
    ok("automorphisms of (Q0, gamma) = Jacobi group, r forced", all(sg.values()))
    hi = holonomy_index()
    ok("<T1, T2> = ker chi, index 12", hi["proved"])
    lc = levi_lift_control()
    ok("control: Levi lifts have chi = (4, 9), cusp rank 1",
       lc["chi"] == (4, 9) and lc["rank N"] == 1)
    za = zariski_lie_algebra()
    ok("Zariski closure: Lie algebra dim 6 = stabiliser", za["dense"])
    pa = period_domain_action()
    ok("G(R) keeps the 6 mu shape and preserves D",
       all(v["shape_ok"] and v["D_invariant"] for v in pa.values()))
    sd = stabiliser_dimension()
    ok("orbit dim 5, stabiliser SO(2)", sd["orbit_dim"] == 5
       and sd["rotation_fixes_point"])
    cd = class_divisibility(box)
    ok("four classes = d in {1,2,3,6}, Pf 6; d | p, least |p| = d",
       cd["d_values"] == [1, 2, 3, 6] and cd["pfaffians"] == [6]
       and cd["d_divides_p"] and cd["gcd_equals_d"]
       and cd["least_|p|_equals_d"] and cd["paper"] == (1, 6))
    for name, c in checks:
        print("  {:<62} {}".format(name, "ok" if c else "FAIL"))
    return all(c for _, c in checks)


