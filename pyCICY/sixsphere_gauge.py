def levi(M):
    """L(M): M in SL(2) acting on <u, w>, gamma and delta fixed."""
    A = eye(4)
    A[1:3, 1:3] = Matrix(M)
    return A


def heis(c1, c2, s):
    """h(c, s): the Heisenberg element with translation c and centre s."""
    return Matrix([[1, -6 * c2, 6 * c1, s], [0, 1, 0, c1],
                   [0, 0, 1, c2], [0, 0, 0, 1]])


def split(g):
    """g = L(M) h(c, s); returns (M, (c1, c2, s)), or raises if g is not in G."""
    g = Matrix(g)
    M = g[1:3, 1:3]
    h = levi(M).inv() * g
    c1, c2, s = h[1, 3], h[2, 3], h[0, 3]
    if h != heis(c1, c2, s):
        raise ValueError("not an automorphism of (Q0, gamma)")
    return M, (c1, c2, s)


