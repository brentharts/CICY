def structure_group():
    r"""Solve g gamma = gamma, g^t Q0 g = Q0 for g in the flag shape.

    Every automorphism of (Q0, gamma) fixes gamma and, since delta^ =
    Q0(gamma, .), fixes delta^ too, so it has first column e0 and last row
    e3. Solving the quadratic system for the remaining entries gives the
    Jacobi group: M in SL(2), the row r forced to (-6 c2, 6 c1) M, s free.
    """
    a, b, c, d, r1, r2, s, c1, c2 = symbols("a b c d r1 r2 s c1 c2")
    G = Matrix([[1, r1, r2, s], [0, a, b, c1], [0, c, d, c2], [0, 0, 0, 1]])
    Ggen = levi(Matrix([[a, b], [c, d]])) * heis(c1, c2, s)
    # the general element L(M) h(c, s), with det M = 1 imposed
    sub = {a: (1 + b * c) / d}
    lhs = (Ggen.T * S.Q0 * Ggen - S.Q0).subs(sub).applyfunc(cancel)
    # and conversely: the Q0 condition on the flag shape forces r
    sols = linsolve(list((G.T * S.Q0 * G - S.Q0).subs(sub)), [r1, r2])
    r_forced = list(sols)[0]
    r_want = (Matrix([[-6 * c2, 6 * c1]]) * Matrix([[a, b], [c, d]])).subs(sub)
    r_ok = all(cancel(x - y) == 0 for x, y in zip(r_forced, r_want))
    # the Heisenberg law
    x1, x2, y1, y2, s1, s2 = symbols("x1 x2 y1 y2 s1 s2")
    law = heis(x1, x2, s1) * heis(y1, y2, s2) == heis(
        x1 + y1, x2 + y2, s1 + s2 + 6 * (x1 * y2 - x2 * y1))
    return {"L(M) h(c, s) preserves Q0": lhs == zeros(4),
            "r forced = (-6 c2, 6 c1) M": r_ok,
            "heisenberg law, centre 6 omega": law,
            "T1 in G": _in_G(S.T1), "T2 in G": _in_G(S.T2)}


def _in_G(g):
    g = Matrix(g)
    return (g * Matrix([1, 0, 0, 0]) == Matrix([1, 0, 0, 0])
            and g.T * S.Q0 * g == S.Q0)


