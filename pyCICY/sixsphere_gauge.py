r"""
pyCICY.sixsphere_gauge -- the six-sphere's torus fibres as a structure, and
their holonomy as a subgroup of its automorphisms (Part IX).

H. Gomes, *Gauge Theory Without Principal Fiber Bundles* (Philosophy of
Science 92 (2025) 511-527), proposes to start from vector bundles whose fibres
carry a structure, to *derive* the gauge group as the automorphism group of
that structure, and to see the structure group reappear as a holonomy group.
Alpoge's threefold X is a family of complex 2-tori over P^1 whose integral
homology is a flat local system with monodromy T1, T2 (:mod:`pyCICY.sixsphere`).
That is exactly such a bundle, with a discrete fibre V = Z^4, and the question
Gomes's programme asks of it is finite:

    which structure does every fibre carry, what is its automorphism group,
    and how much of that group does the holonomy actually reach?

Everything below is exact.

1. **The structure** (:func:`invariant_tensors`). The tensors of degree at
   most two fixed by both generators are: the vector gamma in V; the covector
   delta^ in V*; the alternating form Q0 (unique up to scale, Part I) and its
   dual bivector eta in V (x) V; gamma^2 in S^2 V and delta^^2 in S^2 V*; and
   the commutant <I, gamma (x) delta^>. They are not independent: eta = *Q0
   (Part I) and delta^ = Q0(gamma, .). So the structure is the pair
   (Q0, gamma): a symplectic lattice with a marked vector.

2. **The derived gauge group** (:func:`structure_group`). The automorphisms
   of (Q0, gamma) are, in the basis (gamma, u, w, delta),

       g = L(M) h(c, s),   h(c, s) = [[1, -6 c2, 6 c1, s],
                                      [0,  1,    0,   c1],
                                      [0,  0,    1,   c2],
                                      [0,  0,    0,   1 ]],

   M in SL(2, Z), c in Z^2, s in Z: the integral *Jacobi group*
   SL(2, Z) |x Heis, with the Heisenberg law
   h(c, s) h(c', s') = h(c + c', s + s' + 6 omega(c, c')). This is the
   flag-class shape that :mod:`pyCICY.sixsphere_search` takes from Lemma
   2.7 (iii) -- derived here from the structure, and with one difference: the
   structure *forces* the row r = (-6 c2, 6 c1) M, which the flag class leaves
   free.

3. **The holonomy group has index 12** (:func:`holonomy_index`). Let
   alpha: SL(2, Z) -> Z/12 be the abelianisation (S -> 9, T -> 1; the
   presentation <S, T | S^4, (ST)^3 S^-2> is quoted), and on the Heisenberg
   group let

       f(h(c, s)) = s - 6 q(c)  mod 12,   q(c) = 0 if c = 0 mod 2, else 1,

   the odd quadratic refinement of omega mod 2. f is a homomorphism (a
   16-case check mod 2) and is invariant under SL(2, Z) (because
   L(M) h(c, s) L(M)^-1 = h(Mc, s), checked symbolically), so
   chi(L(M) h) = alpha(M) + f(h) is a character of the Jacobi group. Then

       chi(T1) = 4 + 8 = 0,  chi(T2) = 9 + 3 = 0,  chi(z) = 1  for z = h(0, 0, 1),

   and the holonomy group <T1, T2> is *exactly* ker chi: a normal subgroup of
   index 12 with cyclic quotient, generated mod H by the central transvection
   z: delta -> delta + gamma. The proof is finite and is carried out by
   :func:`holonomy_index`: H maps onto SL(2, Z) (M1 M2 = T, M2 = S); explicit
   words put h(1, 0, 6), h(0, 1, 6) and hence z^12 in H; those generate
   ker chi restricted to the Heisenberg group; so ker chi is contained in H,
   and H in ker chi because chi kills both generators.

   In Gomes's terms: the structure group that a principal-bundle presentation
   would postulate is the Jacobi group; the holonomy recovers it only up to
   Z/12, and what it misses is precisely the central translations
   delta -> delta + k gamma with 12 not dividing k. The Levi lifts L(M1),
   L(M2) -- the "untwisted" choice -- have chi = 4 and 9, generate a
   complement isomorphic to SL(2, Z), and fail the cusp condition; the
   Heisenberg parts of T1 and T2 are what cancel the eta-character alpha.

4. **Zariski density** (:func:`zariski_lie_algebra`). The Lie algebra
   generated by the logarithms of unipotent elements of H (the cusp T0 and the
   commutator [T2^2, T1]) under conjugation has dimension 6 and equals the Lie
   algebra of the real stabiliser of (Q0, gamma), sl(2) |x heis(3). So the
   real Zariski closure of the holonomy is the full real Jacobi group.

5. **The real group on the period domain** (:func:`period_domain_action`).
   Feeding one-parameter subgroups of the real Jacobi group through
   :func:`pyCICY.sixsphere.laws_from_lattice` -- the routine that derives the
   period laws from a matrix -- gives the classical Jacobi action on
   (tau, mu, beta): mu -> mu + t, mu -> mu - t tau, beta -> beta + t, and
   SL(2, R) by Moebius maps. Every one of them keeps the 6 mu shape and
   preserves D = Im beta - 6 (Im mu)^2 / Im tau. The orbit of a point has
   real dimension 5 and its stabiliser is a circle SO(2) (computed at
   (i, 0, i D)): the level sets of D are G(R)/SO(2). The compact group the
   structure-first reading derives at a point is U(1), even though the Hodge
   form on F^1 is indefinite (signature (1, 1), Part II).

6. **The four near-miss classes are the four divisibilities of gamma**
   (:func:`class_divisibility`). Part VII found four GL(4, Z) classes of
   flag-class data, distinguished by the reachable |p| mod 12. Each class has
   a primitive invariant alternating form Q with Pfaffian 6, and the
   divisibility d of the functional Q(gamma, .) is 1, 2, 3 or 6 -- the four
   ordered factorisations (d, 6/d) of 6, eight survivors each. On every
   survivor of the funnel, d divides every reachable p and the least nonzero
   |p| is d (the mechanism: 3 | d forces 3 | l1, 2 | d forces l2 even). So
   the paper's class is the one in which gamma is *unimodularly* paired by
   the structure, and the near misses bottom out at |p| = 3, 2, 6 because d
   divides p. In all four
   classes the central transvection first enters the holonomy at z^12
   (observed by a word search; proved above for the paper's class).

What is not claimed: anything analytic (the period functions, and so whether
the near-miss classes carry complex manifolds, stay declined as in Part VII);
that Gomes's philosophical claims are right or wrong -- only that his recipe
can be run here, and what it returns. The presentation of SL(2, Z) is quoted.
The reading of chi as the eta^2 multiplier times an odd theta characteristic
is a remark, not computed.
"""

