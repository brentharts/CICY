def _invariant_space(eq, n=16):
    xs = symbols("x0:%d" % n)
    X = Matrix(4, 4, xs) if n == 16 else Matrix(4, 1, xs)
    eqs = []
    for T in (S.T1, S.T2):
        eqs += list(eq(T, X))
    sol = list(linsolve(eqs, xs))[0]
    free = sorted(set().union(*[e.free_symbols for e in sol]), key=str)
    basis = []
    for k in range(len(free)):
        sub = {x: (1 if i == k else 0) for i, x in enumerate(free)}
        basis.append(Matrix(X.shape[0], X.shape[1], [e.subs(sub) for e in sol]))
    return basis


def invariant_tensors():
    r"""Every tensor of degree <= 2 fixed by T1 and T2, solved for.

    V: T x = x.  V*: T^t y = y.  V (x) V: T X T^t = X.  V* (x) V*: T^t X T = X.
    End V: T X = X T. Returns bases, their dimensions, and the relation
    delta^ = Q0(gamma, .).
    """
    out = {
        "V": _invariant_space(lambda T, x: T * x - x, 4),
        "V*": _invariant_space(lambda T, x: T.T * x - x, 4),
        "VV": _invariant_space(lambda T, X: T * X * T.T - X),
        "V*V*": _invariant_space(lambda T, X: T.T * X * T - X),
        "End": _invariant_space(lambda T, X: T * X - X * T),
    }
    dims = {k: len(v) for k, v in out.items()}
    gamma = Matrix([1, 0, 0, 0])
    delta_hat = Matrix([0, 0, 0, 1])
    sym = [B for B in out["V*V*"] if B == B.T]
    alt = [B for B in out["V*V*"] if B == -B.T]
    return {
        "bases": out, "dims": dims,
        "V_is_gamma": len(out["V"]) == 1 and out["V"][0] == gamma,
        "V*_is_delta_hat": len(out["V*"]) == 1 and out["V*"][0] == delta_hat,
        "alternating_is_Q0": len(alt) == 1 and alt[0] in (S.Q0, -S.Q0),
        "symmetric_V*V*": sym,
        "commutant_is_I_and_gamma_delta": dims["End"] == 2,
        "delta_hat = Q0(gamma, .)": (gamma.T * S.Q0).T == delta_hat,
    }


