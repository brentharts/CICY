def _log_unipotent(U):
    N = U - eye(4)
    out = zeros(4)
    P = eye(4)
    for k in range(1, 5):
        P = P * N
        out += Rational((-1) ** (k + 1), k) * P
    return out


def _span_rank(mats):
    if not mats:
        return 0
    return Matrix([list(m) for m in mats]).rank()


def zariski_lie_algebra(max_rounds=6):
    r"""Close {log T0, log [T2^2, T1]} under conjugation by T1, T2 and
    brackets; compare with the Lie algebra of the real stabiliser of
    (Q0, gamma): X gamma = 0, X^t Q0 + Q0 X = 0."""
    T0 = (S.T1 * S.T2).inv()
    C = S.T2 ** 2 * S.T1 * S.T2 ** -2 * S.T1.inv()
    basis = [_log_unipotent(T0), _log_unipotent(C)]
    conj = [S.T1, S.T2, S.T1.inv(), S.T2.inv()]
    for _ in range(max_rounds):
        r0 = _span_rank(basis)
        new = list(basis)
        for X in basis:
            for g in conj:
                new.append(g * X * g.inv())
        for X, Y in itertools.combinations(basis, 2):
            new.append(X * Y - Y * X)
        # keep an independent subset
        keep = []
        for X in new:
            if _span_rank(keep + [X]) > len(keep):
                keep.append(X)
        basis = keep
        if _span_rank(basis) == r0:
            break
    xs = symbols("y0:16")
    X = Matrix(4, 4, xs)
    eqs = list(X * Matrix([1, 0, 0, 0])) + list(X.T * S.Q0 + S.Q0 * X)
    sol = list(linsolve(eqs, xs))[0]
    stab_dim = len(set().union(*[e.free_symbols for e in sol]))
    inside = all(B * Matrix([1, 0, 0, 0]) == zeros(4, 1)
                 and B.T * S.Q0 + S.Q0 * B == zeros(4) for B in basis)
    return {"dim generated": len(basis), "dim stabiliser": stab_dim,
            "inside stabiliser": inside,
            "dense": len(basis) == stab_dim and inside}


