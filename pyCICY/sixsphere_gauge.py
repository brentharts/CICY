def q_odd(c):
    """The odd quadratic refinement of omega mod 2: 0 on 2Z^2, 1 elsewhere."""
    return 0 if (int(c[0]) % 2 == 0 and int(c[1]) % 2 == 0) else 1


def f_heis(c1, c2, s):
    """f(h(c, s)) = s - 6 q(c) mod 12."""
    return (int(s) - 6 * q_odd((c1, c2))) % 12


def f_is_homomorphism():
    r"""f(h h') = f(h) + f(h') mod 12, for all h, h'.

    f(h h') - f(h) - f(h') = 6 [omega(c, c') - q(c + c') + q(c) + q(c')], and
    the bracket depends only on c, c' mod 2: sixteen cases, each checked.
    """
    bad = []
    for c, cp in itertools.product(itertools.product((0, 1), repeat=2),
                                   repeat=2):
        om = c[0] * cp[1] - c[1] * cp[0]
        cc = (c[0] + cp[0], c[1] + cp[1])
        if (6 * (om - q_odd(cc) + q_odd(c) + q_odd(cp))) % 12:
            bad.append((c, cp))
    return {"cases": 16, "failures": bad, "ok": not bad}


def f_is_invariant():
    r"""L(M) h(c, s) L(M)^-1 = h(Mc, s), symbolically; and q(Mc) = q(c)
    because M is invertible mod 2. So f is SL(2, Z)-invariant."""
    a, b, c, d, c1, c2, s = symbols("a b c d c1 c2 s")
    M = Matrix([[a, b], [c, d]])
    sub = {a: (1 + b * c) / d}
    lhs = (levi(M) * heis(c1, c2, s) * levi(M).inv()).subs(sub)
    Mc = (M * Matrix([c1, c2])).subs(sub)
    rhs = heis(Mc[0], Mc[1], s)
    conj_ok = (lhs - rhs).applyfunc(cancel) == zeros(4)
    q_ok = all(q_odd((m[0] * x + m[1] * y, m[2] * x + m[3] * y)) == q_odd((x, y))
               for m in itertools.product((0, 1), repeat=4)
               if (m[0] * m[3] - m[1] * m[2]) % 2
               for x, y in itertools.product((0, 1), repeat=2))
    return {"conjugation h(c,s) -> h(Mc,s)": conj_ok,
            "q is GL(2, F2)-invariant": q_ok}


#: alpha on the generators S, T of SL(2, Z). Quoted presentation
#: <S, T | S^4 = 1, (S T)^3 = S^2>; the two relations hold in Z/12.
ALPHA = {"S": 9, "T": 1}


def alpha():
    """The abelianisation SL(2, Z) -> Z/12: the relations, and its values."""
    s, t = ALPHA["S"], ALPHA["T"]
    rel = {"S^4": (4 * s) % 12 == 0, "(ST)^3 = S^2": (3 * (s + t) - 2 * s) % 12 == 0,
           "matrices satisfy the relations": (_ST ** 4 == eye(2)
                                              and (_ST * _TT) ** 3 == _ST ** 2)}
    # M2 = S, M1 = T S^-1 (since M1 M2 = T)
    words = {"M2 = S": _M2 == _ST, "M1 = T S^-1": _M1 == _TT * _ST.inv()}
    vals = {"M1": (t - s) % 12, "M2": s % 12, "T": t % 12}
    return {"relations": rel, "words": words, "values": vals}


def sl2_word_alpha(word):
    """alpha of a word in 'S', 's' (= S^-1), 'T', 't' (= T^-1)."""
    v = {"S": ALPHA["S"], "s": -ALPHA["S"], "T": ALPHA["T"], "t": -ALPHA["T"]}
    return sum(v[x] for x in word) % 12


def chi(g, alpha_M=None):
    """chi(L(M) h(c, s)) = alpha(M) + f(h). alpha(M) must be supplied unless M
    is one of M1, M2, T, I, -I, S (the values the checks need)."""
    M, (c1, c2, s) = split(g)
    if alpha_M is None:
        table = [(eye(2), 0), (-eye(2), 6), (_M1, 4), (_M1 ** 2, 8), (_M2, 9),
                 (_M2 ** 2, 6), (_M2 ** 3, 3), (_TT, 1), (_TT.inv(), 11)]
        hit = [v for m, v in table if m == M]
        if not hit:
            raise ValueError("alpha(M) not tabulated; pass alpha_M")
        alpha_M = hit[0]
    return (alpha_M + f_heis(c1, c2, s)) % 12


#: Words in a = T1, A = T1^2, b = T2, B = T2^3 found by a breadth-first search.
WORDS = {"h(0,1,6)": "babbAb", "h(-1,0,6)": "bbabbA",
         "h(1,0,6)": "Abbabbabbabba"}


def word_matrix(word):
    g = {"a": S.T1, "A": S.T1 ** 2, "b": S.T2, "B": S.T2 ** 3}
    out = eye(4)
    for x in word:
        out = out * g[x]
    return out


def holonomy_index():
    r"""Prove <T1, T2> = ker chi, of index 12 in the integral Jacobi group.

    (i)   chi(T1) = chi(T2) = 0, so H is in ker chi;
    (ii)  M1, M2 generate SL(2, Z) (they are T S^-1 and S), so H maps onto it;
    (iii) the words in WORDS give h(1,0,6), h(0,1,6), h(-1,0,6) in H, and
          h(1,0,6) h(-1,0,6) = z^12;
    (iv)  {h : f(h) = 0} is generated by h(1,0,6), h(0,1,6), z^12 (any h with
          f(h) = 0 is h(1,0,6)^c1 h(0,1,6)^c2 times a power of z^12, as f is a
          homomorphism and these map to 0 with independent c);
    (v)   given g in ker chi pick h in H with the same M; h^-1 g is a
          Heisenberg element with f = 0, hence in H.
    So H = ker chi; chi(z) = 1 makes chi onto Z/12.
    """
    a = alpha()
    c1, c2 = chi(S.T1), chi(S.T2)
    words = {k: word_matrix(w) for k, w in WORDS.items()}
    words_ok = {k: words[k] == heis(*[int(x) for x in k[2:-1].split(",")])
                for k in words}
    z12 = words["h(1,0,6)"] * words["h(-1,0,6)"]
    # (iv): reduce an arbitrary f = 0 element; check it on a box
    gens = (heis(1, 0, 6), heis(0, 1, 6), heis(0, 0, 12))
    box_ok = True
    for x, y in itertools.product(range(-3, 4), repeat=2):
        for s in range(-24, 25):
            if f_heis(x, y, s):
                continue
            g = (gens[0] ** x if x >= 0 else gens[0].inv() ** (-x))
            g = g * (gens[1] ** y if y >= 0 else gens[1].inv() ** (-y))
            rest = g.inv() * heis(x, y, s)
            if not (rest[1, 3] == 0 and rest[2, 3] == 0 and rest[0, 3] % 12 == 0):
                box_ok = False
    return {"chi(T1)": c1, "chi(T2)": c2,
            "chi(T0^-1 = T1 T2)": chi(S.T1 * S.T2),
            "chi(z)": chi(heis(0, 0, 1)),
            "alpha": a, "f_hom": f_is_homomorphism()["ok"],
            "f_invariant": all(f_is_invariant().values()),
            "words_ok": all(words_ok.values()),
            "z^12 in H": z12 == heis(0, 0, 12),
            "f=0 generated (box)": box_ok,
            "index": 12,
            "proved": (c1 == 0 and c2 == 0 and all(words_ok.values())
                       and z12 == heis(0, 0, 12) and box_ok
                       and chi(heis(0, 0, 1)) == 1
                       and all(a["relations"].values())
                       and all(a["words"].values()))}


def levi_lift_control():
    r"""The untwisted lifts L(M1), L(M2): orders 3 and 4, chi = 4 and 9, and
    their product L(T) is unipotent of rank 1, not 2 -- the cusp fails."""
    L1, L2 = levi(_M1), levi(_M2)
    N = (L1 * L2).inv() - eye(4)
    return {"orders": (L1 ** 3 == eye(4), L2 ** 4 == eye(4)),
            "chi": (chi(L1), chi(L2)),
            "rank N": N.rank(), "N^2 = 0": N * N == zeros(4)}


